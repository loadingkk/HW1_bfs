import argparse
import csv
from collections import defaultdict
from pathlib import Path

try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
except ModuleNotFoundError as exc:
    raise SystemExit(
        "matplotlib is required for plotting. Install it with: python3 -m pip install matplotlib"
    ) from exc


DEFAULT_CSV_PATH = Path(__file__).resolve().parent / "benchmark_summary.csv"
DEFAULT_PLOT_PATH = Path(__file__).resolve().parent / "benchmark_comparison.png"


def load_rows(csv_path):
    with csv_path.open("r", encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def aggregate_by_scale(rows, metric):
    aggregated = defaultdict(dict)
    for row in rows:
        scale = int(row["scale"])
        implementation = row["implementation"]
        aggregated[scale][implementation] = float(row[metric])
    return aggregated


def make_plot(rows, output_path, metric):
    aggregated = aggregate_by_scale(rows, metric)
    scales = sorted(aggregated.keys())

    plain_values = [aggregated[scale].get("plain_bfs") for scale in scales]
    mr_values = [aggregated[scale].get("mapreduce_bfs") for scale in scales]

    plt.figure(figsize=(8, 5))
    plt.plot(scales, plain_values, marker="o", linewidth=2, label="Plain BFS")
    plt.plot(scales, mr_values, marker="s", linewidth=2, label="MapReduce-style BFS")
    plt.xlabel("Scale (graph size = 2^scale)")
    plt.ylabel(f"{metric.replace('_', ' ').title()}")
    plt.title("Python BFS vs MapReduce-style BFS by Scale")
    plt.grid(True, alpha=0.3)
    plt.legend()
    plt.tight_layout()

    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=160)
    plt.close()


def parse_args():
    parser = argparse.ArgumentParser(
        description="Plot benchmark results for plain BFS vs MapReduce-style BFS."
    )
    parser.add_argument(
        "--csv",
        type=Path,
        default=DEFAULT_CSV_PATH,
        help="Summary CSV generated by the benchmark runner.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_PLOT_PATH,
        help="Output image path.",
    )
    parser.add_argument(
        "--metric",
        choices=["min_seconds", "median_seconds", "mean_seconds"],
        default="median_seconds",
        help="Summary metric to plot.",
    )
    return parser.parse_args()


def main():
    args = parse_args()
    rows = load_rows(args.csv)
    if not rows:
        raise ValueError(f"No rows found in {args.csv}")
    make_plot(rows, args.output, args.metric)
    print(f"Saved plot to {args.output}")


if __name__ == "__main__":
    main()
